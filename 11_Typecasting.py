#Type casting for list

#string to list
a="python"
print(list(a))
       #OR
b=input("enter a word:")
print(list(b))

#tuple to list
c=("python","JAVA","C++","HTML")
print(list(c))

#set to list
d={"blue","pink","red","black"}
print(list(d))

#list to tuple
c=["python","JAVA","C++","HTML"]
print(tuple(c))

#set to list
d=["blue","pink","red","black"]
print(set(d))
